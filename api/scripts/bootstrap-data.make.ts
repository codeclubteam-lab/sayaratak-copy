import { buildSeed } from "../../web/src/mocks/seed"

type Seed = ReturnType<typeof buildSeed>
type SitePage = Seed["pages"][number]

/** The reference data production starts from: no people, listings or activity (A2). */
export type BootstrapData = Pick<
  Seed,
  | "countries"
  | "taxonomy"
  | "plans"
  | "promotionPrices"
  | "adPages"
  | "settings"
> & {
  // No `updatedAt`: the mock dates pages relative to now, which would make the file change on
  // every run. Bootstrap stamps them when it writes them.
  pages: Omit<SitePage, "updatedAt">[]
}

export const BOOTSTRAP_DATA_FILE = `${import.meta.dir}/bootstrap-data.ts`

/**
 * `bun run bootstrap:data`: writes the reference part of the mock seed as a typed module, so the
 * production image runs bootstrap without web code or faker. The file is committed;
 * tests/bootstrap.test.ts fails when it is stale.
 */
export function renderBootstrapData() {
  const seed = buildSeed({ empty: true })
  const data: BootstrapData = {
    countries: seed.countries,
    taxonomy: seed.taxonomy,
    plans: seed.plans,
    promotionPrices: seed.promotionPrices,
    adPages: seed.adPages,
    settings: seed.settings,
    pages: seed.pages.map(({ updatedAt: _, ...page }) => page),
  }
  return [
    "// Generated by `bun run bootstrap:data` from the mock seed. Do not edit.",
    'import type { BootstrapData } from "./bootstrap-data.make"',
    "",
    `export const bootstrapData: BootstrapData = ${JSON.stringify(data, null, 2)}`,
    "",
  ].join("\n")
}

if (import.meta.main)
  await Bun.write(BOOTSTRAP_DATA_FILE, renderBootstrapData())
